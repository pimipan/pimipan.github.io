#!/usr/bin/env python3
"""Build the cleanroom page from Markdown using the repository project template.
Run from the repository: python3 scripts/sync-cleanroom.py
Requires the project's existing Ruby bundle (Kramdown).
"""
from pathlib import Path
import html
import json
import re
import subprocess

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'projects/洁净室建设项目经历分享.md'
OUTPUT = ROOT / 'projects/cleanroom-laboratory.html'
source = SOURCE.read_text()
parts = re.split(r'^## (.+)\n', source, flags=re.M)
sections = [(parts[i], parts[i + 1].strip()) for i in range(1, len(parts), 2)]
if len(sections) != 6:
    raise ValueError('Expected the six project sections; review the source before rendering.')

def esc(text):
    return html.escape(text, quote=True)

# Use the site's existing Markdown renderer; keep the author's wording intact.
ruby = '''require 'json'; require 'kramdown'; require 'kramdown-parser-gfm'
puts 'CLEANROOM_JSON:' + JSON.generate(JSON.parse(STDIN.read).map { |s| Kramdown::Document.new(s, input: 'GFM', hard_wrap: true).to_html })'''
rendered = json.loads(subprocess.run(
    ['bundle', 'exec', 'ruby', '-e', ruby], input=json.dumps([b for _, b in sections]),
    cwd=ROOT, text=True, capture_output=True, check=True,
).stdout.split('CLEANROOM_JSON:', 1)[1])

def rows(markdown):
    result = []
    for line in markdown.splitlines():
        if line.startswith('|'):
            cells = [v.strip() for v in line.strip().strip('|').split('|')]
            if not all(re.fullmatch(r':?-+:?', v) for v in cells):
                result.append(cells)
    return result

ids = ['overview', 'stakeholders', 'process', 'issues', 'priorities', 'reflection']
nav = '<nav class="project-index" aria-label="正文目录">' + ''.join(
    f'<a href="#{id}">{esc(re.sub(r"^[一二三四五六]、", "", title))}</a>'
    for id, (title, _) in zip(ids, sections)
) + '</nav>'

# The overview remains the source paragraph, with the project role from its title.
content = '<div class="project-document">' + nav
for i, ((title, markdown), fragment) in enumerate(zip(sections, rendered)):
    if i == 1:
        table = rows(markdown)
        labels = table[0]
        if any(len(row) != len(labels) for row in table):
            raise ValueError('Stakeholder table has inconsistent columns.')
        table_html = '<div class="stakeholder-table"><table><thead><tr>' + ''.join(f'<th scope="col">{esc(v)}</th>' for v in labels) + '</tr></thead><tbody>'
        for row in table[1:]:
            table_html += '<tr><th scope="row">' + esc(row[0]) + '</th>'
            table_html += ''.join(f'<td data-label="{esc(label)}">{esc(v)}</td>' for label, v in zip(labels[1:], row[1:])) + '</tr>'
        table_html += '</tbody></table></div>'
        fragment = re.sub(r'<table>.*?</table>', lambda _: table_html, fragment, flags=re.S)
    elif i == 2:
        table = rows(markdown)
        if any(len(row) != 3 for row in table):
            raise ValueError('Process table must have three columns.')
        fragment = '<ol class="project-process">'
        for row in table[1:]:
            match = re.match(r'(\d+)\s+(.*)', row[0])
            number, name = match.groups()
            fragment += f'<li><span class="process-number" aria-hidden="true">{esc(number)}</span><div class="process-work"><h3>{esc(name)}</h3><span class="process-label">{esc(table[0][1])}</span><p>{esc(row[1])}</p></div><div class="process-evidence"><span>{esc(table[0][2])}</span><p>{esc(row[2])}</p></div></li>'
        fragment += '</ol>'
    elif i == 3:
        chunks = re.split(r'(?=<h3\b)', fragment)
        fragment = chunks[0] + '<div class="project-cases">' + ''.join('<article class="project-case">' + c + '</article>' for c in chunks[1:]) + '</div>'
    elif i == 4:
        chunks = re.split(r'(?=<h3\b)', fragment)
        fragment = chunks[0] + ''.join('<div class="priority-topic">' + c + '</div>' for c in chunks[1:])
    content += f'<section class="project-section section-{ids[i]}" id="{ids[i]}" aria-labelledby="heading-{ids[i]}"><h2 id="heading-{ids[i]}">{esc(title)}</h2><div class="project-copy">{fragment}</div></section>'
content += '</div>'

template = (ROOT / 'projects/project-template.html').read_text()
template = re.sub(r'^---\n.*?\n---\n', '''---
layout: null
permalink: /projects/cleanroom-laboratory/
title: 洁净室建设项目管理
summary: >-
  电池实验室洁净区建设：统筹利益相关方、设计施工节点与调试交付，记录甲方项目管理实践。
order: 2
listed: true
tags:
  - Cleanroom
  - Laboratory
  - Project Management
---
''', template, count=1, flags=re.S)
template = re.sub(r'<!-- 复制此文件.*?-->', '<!-- Generated by scripts/sync-cleanroom.py from the adjacent Markdown. -->', template, count=1, flags=re.S)
template = template.replace('</head>', '<link rel="stylesheet" href="{{ "/assets/css/cleanroom-project.css" | relative_url }}">\n</head>')
template = template.replace('<h1>{{ page.title }}</h1>', '<div class="project-title"><h1>洁净室建设项目管理</h1></div>')
template = template.replace('<p>在这里添加项目详细内容。</p>', content)
temporary = OUTPUT.with_suffix('.html.tmp')
temporary.write_text(template)
temporary.replace(OUTPUT)
print(OUTPUT)
